/**
 * تطبيع مدخلات الزبون، ومطابقة الأوامر الثلاثة.
 *
 * 🔴 **دالة تطبيع واحدة في المشروع كله.** كل مطابقة تمر من `normalizeArabic`.
 *    نسخة ثانية معناها أن قائمة تُطبَّع بقاعدة ومدخل الزبون بقاعدة أخرى،
 *    فالمطابقة تفشل على مدخل صحيح — بلا خطأ ولا سقوط اختبار.
 *
 * ⚠️ **الكلمات العامية هنا مدخلات، لا مخارج.**
 *    قائمة ممنوعات اللهجة (عم · هلق · شو · بدي · رح…) تحكم **النص الصادر
 *    فقط** — وهو في `domain.ts`. وهذا الملف عمدا ليس هناك: `domain.ts` يمنع
 *    اللهجة، فوضع `هيك` و`بس` فيه يدعو من يقرأه لاحقا إلى شطبهما.
 *    🔴 **لا أحد يشطب `هيك` و`بس` بحجة «اللهجة ممنوعة». هذا التحذير مقصود.**
 */

/** الأمر الذي عناه الزبون برسالته كاملة، أو `null` إن لم تكن أمرا. */
export type CustomerCommand = "finish" | "cart" | "menu";

// ---------------------------------------------------------------------------
// التطبيع
// ---------------------------------------------------------------------------

/** التشكيل U+064B–U+0652، والتطويل U+0640. تُحذف كلها. */
const DIACRITICS_AND_TATWEEL = /[ً-ْـ]/gu;

/** الأرقام العربية-الهندية ٠-٩ = U+0660–U+0669. */
const ARABIC_INDIC_DIGITS = /[٠-٩]/gu;

/** كل ما ليس حرفا ولا رقما، على الطرفين فقط: ترقيم · إيموجي · رموز · مسافات. */
const NON_ALNUM_HEAD = /^[^\p{L}\p{N}]+/u;
const NON_ALNUM_TAIL = /[^\p{L}\p{N}]+$/u;

/**
 * الشكل المعياري لمدخل الزبون. سبع خطوات بالترتيب:
 *
 *   1. `أ إ آ` → `ا`
 *   2. `ة` → `ه`
 *   3. `ى` → `ي`
 *   4. حذف التشكيل والتطويل
 *   5. `٠-٩` → `0-9`
 *   6. تقليص المسافات المتعددة إلى واحدة
 *   7. قص الترقيم والإيموجي من الطرفين، ثم القص النهائي
 *
 * بعدها: `إنهاء` = `انهاء` · `تم.` = `تم` · `تم 👍` = `تم` · `كفاية` = `كفايه`.
 *
 * 🔴 الخطوة 5 **تطبيع مدخلات، لا مخرجات.** الزبون الأردني على لوحة مفاتيح
 *    عربية يرسل `٥` لا `5`، وبدونها طلبه يسقط كاملا وبلا تفسير. قاعدة
 *    «الأرقام غربية» تحكم ما نرسله نحن، وهذا ما نستقبله.
 *
 * 🔴 القص من الطرفين فقط. `هاد كل شي` مسافاته داخلية وتبقى — تقليصها إلى
 *    مسافة واحدة كافٍ، وحذفها يخلط الأمر بغيره.
 */
export function normalizeArabic(input: string): string {
  return input
    .replace(/[أإآ]/gu, "ا") // أ إ آ → ا
    .replace(/ة/gu, "ه") // ة → ه
    .replace(/ى/gu, "ي") // ى → ي
    .replace(DIACRITICS_AND_TATWEEL, "")
    .replace(ARABIC_INDIC_DIGITS, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/\s+/gu, " ")
    .replace(NON_ALNUM_HEAD, "")
    .replace(NON_ALNUM_TAIL, "");
}

// ---------------------------------------------------------------------------
// القوائم — مخزّنة **مطبَّعة**
// ---------------------------------------------------------------------------
//
// 🔴 مدخل غير مطبَّع في هذه القوائم لا يطابق شيئا أبدا: المدخل يُطبَّع والقائمة
//    لا، فالمقارنة تفشل صامتة. `COMMAND_INPUT_LISTS` تحت مصدَّرة لهذا: اختبار
//    واحد يمشي على القوائم الثلاث مدخلا مدخلا ويؤكد أن كلا منها نقطة ثابتة
//    لـ`normalizeArabic`. والشكلان لا يُخزَّنان معا — شكل واحد مطبَّع، وهو المرجع.
// ---------------------------------------------------------------------------

/** إنهاء الطلب. اللهجة الأردنية الحقيقية مقبولة لأن المطابقة على الرسالة كاملة. */
export const FINISH_INPUTS = [
  "تم",
  "خلص",
  "خلصت",
  "انهاء",
  "بس",
  "كفايه",
  "هيك",
  "هيك بس",
  "هاد كل شي",
] as const;

/** عرض السلّة. */
export const CART_INPUTS = ["سله", "السله"] as const;

/** عرض المنيو من جديد. */
export const MENU_INPUTS = ["منيو", "المنيو", "القائمه"] as const;

const COMMAND_TABLE: ReadonlyArray<
  readonly [CustomerCommand, ReadonlySet<string>]
> = [
  ["finish", new Set<string>(FINISH_INPUTS)],
  ["cart", new Set<string>(CART_INPUTS)],
  ["menu", new Set<string>(MENU_INPUTS)],
];

// ---------------------------------------------------------------------------
// المطابقة
// ---------------------------------------------------------------------------

/**
 * الأمر الذي تعنيه الرسالة **كاملة**، أو `null`.
 *
 * 🔴 **المطابقة على الرسالة كاملة بعد التطبيع. لا على الاحتواء إطلاقا.**
 *    هذه ليست تفضيلا أسلوبيا — `includes` تجعل هاتين تنهيان الطلب:
 *      - `بدي شاورما بس بدون بصل`     ← تحتوي «بس»
 *      - `خلصت من الشغل هلق بدي اطلب` ← تحتوي «خلصت»
 *    الأولى زبون يطلب، والثانية زبون يقول إنه سيطلب. كلتاهما تُنهي طلبا
 *    فارغا أو ناقصا **بلا أي رسالة خطأ**، ولا تُسقط أي اختبار قائم.
 *    ولكل واحدة منهما اختبار سالب باسمها في `test/normalize.test.mts`.
 *
 *    والاحتواء هو ما يجعل قائمة اللهجة قابلة للانفجار: `بس` و`هيك` آمنتان
 *    ككلمة وحيدة، وقنبلتان كجزء من جملة. القيد هو ما يسمح بالقائمة.
 */
export function matchCommand(raw: string): CustomerCommand | null {
  const normalized = normalizeArabic(raw);
  if (normalized === "") return null;

  for (const [command, entries] of COMMAND_TABLE) {
    if (entries.has(normalized)) return command;
  }
  return null;
}

/**
 * كل مدخلات القوائم الثلاث مع أسمائها — للاختبار الذي يثبت أنها مطبَّعة.
 * مصدَّرة عشان الاختبار يمشي على القوائم نفسها، لا على نسخة منها تتقادم.
 */
export const COMMAND_INPUT_LISTS: ReadonlyArray<
  readonly [string, readonly string[]]
> = [
  ["FINISH_INPUTS", FINISH_INPUTS],
  ["CART_INPUTS", CART_INPUTS],
  ["MENU_INPUTS", MENU_INPUTS],
];
