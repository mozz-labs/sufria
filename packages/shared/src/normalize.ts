/**
 * الأمر الذي تعنيه الرسالة **كاملة**، أو `null`.
 *
 * 🔴 **المطابقة على الرسالة كاملة بعد التطبيع. لا على الاحتواء إطلاقا.**
 *    هذه ليست تفضيلا أسلوبيا — `includes` تجعل هاتين تنهيان الطلب:
 *      - `بدي شاورما بس بدون بصل`     ← تحتوي «بس»
 *      - `خلصت من الشغل هلق بدي اطلب` ← تحتوي «خلصت»
 *    الأولى زبون يطلب، والثانية زبون يقول إنه سيطلب. كلتاهما تُنهي طلبا
 *    فارغا أو ناقصا **بلا أي رسالة خطأ**، ولا تُسقط أي اختبار قائم.
 *    ولكل واحدة منهما اختبار سالب باسمها في `test/normalize.test.mts`.
 *
 *    والاحتواء هو ما يجعل قائمة اللهجة قابلة للانفجار: `بس` و`هيك` آمنتان
 *    ككلمة وحيدة، وقنبلتان كجزء من جملة. القيد هو ما يسمح بالقائمة.
 */
export function matchCommand(raw: string): CustomerCommand | null {
  const normalized = normalizeArabic(raw);
  if (normalized === "") return null;

  for (const [command, entries] of COMMAND_TABLE) {
    if (entries.has(normalized)) return command;
  }
  return null;
}

/**
 * أمر ما بعد التصفّح الذي تعنيه الرسالة **كاملة**، أو `null`.
 *
 * 🔴 **نفس قيد `matchCommand`: الرسالة كاملة، لا الاحتواء إطلاقا.** والخطر هنا
 *    أكبر مما هو هناك، لأن المطابقة الخاطئة **تخلق طلبا**:
 *      - `ما بدي اكد`        ← تحتوي «اكد»، وبالاحتواء يصل المطبخ طلب رفضه الزبون
 *      - `بدي اكد بس بعدين`  ← تحتوي «اكد»، والزبون قال صراحة «لاحقا»
 *    ولكل واحدة اختبار سالب باسمها في `test/order-commands.test.mts`.
 *
 *    وهي **لا تعرف** «تم» ولا «سلة» ولا «منيو»: تلك مفردات التصفّح، ومن يريد
 *    الاثنتين معا ينادي المطابقين معا.
 */
export function matchOrderCommand(raw: string): OrderCommand | null {
  const normalized = normalizeArabic(raw);
  if (normalized === "") return null;

  for (const [command, entries] of ORDER_COMMAND_TABLE) {
    if (entries.has(normalized)) return command;
  }
  return null;
}

