/**
 * تطبيع مدخلات الزبون، ومطابقة أوامر التصفّح الأربعة.
 *
 * 🔴 **دالة تطبيع واحدة في المشروع كله.** كل مطابقة تمر من `normalizeArabic`.
 *    نسخة ثانية معناها أن قائمة تُطبَّع بقاعدة ومدخل الزبون بقاعدة أخرى،
 *    فالمطابقة تفشل على مدخل صحيح — بلا خطأ ولا سقوط اختبار.
 *
 * ⚠️ **الكلمات العامية هنا مدخلات، لا مخارج.**
 *    قائمة ممنوعات اللهجة (عم · هلق · شو · بدي · رح…) تحكم **النص الصادر
 *    فقط** — وهو في `domain.ts`. وهذا الملف عمدا ليس هناك: `domain.ts` يمنع
 *    اللهجة، فوضع `هيك` و`بس` فيه يدعو من يقرأه لاحقا إلى شطبهما.
 *    🔴 **لا أحد يشطب `هيك` و`بس` بحجة «اللهجة ممنوعة». هذا التحذير مقصود.**
 */

/** الأمر الذي عناه الزبون برسالته كاملة، أو `null` إن لم تكن أمرا. */
export type CustomerCommand = "finish" | "cart" | "menu" | "reorder";

/**
 * أوامر ما بعد التصفّح: اختيار طريقة الاستلام، وردّ `cart_review` (ج §5).
 *
 * 🔴 **مفصولة عن `CustomerCommand` بقصد. لا تُدمج القائمتان في مطابق واحد.**
 *    لكل حالة مفرداتها، والدمج يجعل كلا منهما تعمل حيث لا يجب بلا رسالة خطأ:
 *      - «اكد» في `browsing` **ليست أمرا** — تنزل للمحلّل كنص غير مفهوم.
 *      - «تم» في `cart_review` **ليست تأكيدا** — هي كلمة الإنهاء في التصفّح
 *        وحده، وهنا يُعاد السؤال (ج §2.3). ولها اختبار سالب باسمها.
 *    والحالة التي تسأل «هل هذه أمر من أي نوع؟» — خطوة العنوان (ج §3) — تنادي
 *    المطابقين معا. وهذا أوضح من مطابق واحد يعرف أكثر مما يجب في كل حالة.
 */
export type OrderCommand =
  "pickup" | "delivery" | "confirm" | "modify" | "cancel";

// ---------------------------------------------------------------------------
// التطبيع
// ---------------------------------------------------------------------------

/** التشكيل U+064B–U+0652، والتطويل U+0640. تُحذف كلها. */
const DIACRITICS_AND_TATWEEL = /[ً-ْـ]/gu;

/** الأرقام العربية-الهندية ٠-٩ = U+0660–U+0669. */
const ARABIC_INDIC_DIGITS = /[٠-٩]/gu;

/** كل ما ليس حرفا ولا رقما، على الطرفين فقط: ترقيم · إيموجي · رموز · مسافات. */
const NON_ALNUM_HEAD = /^[^\p{L}\p{N}]+/u;
const NON_ALNUM_TAIL = /[^\p{L}\p{N}]+$/u;

/**
 * الشكل المعياري لمدخل الزبون. سبع خطوات بالترتيب:
 *
 *   1. `أ إ آ` → `ا`
 *   2. `ة` → `ه`
 *   3. `ى` → `ي`
 *   4. حذف التشكيل والتطويل
 *   5. `٠-٩` → `0-9`
 *   6. تقليص المسافات المتعددة إلى واحدة
 *   7. قص الترقيم والإيموجي من الطرفين، ثم القص النهائي
 *
 * بعدها: `إنهاء` = `انهاء` · `تم.` = `تم` · `تم 👍` = `تم` · `كفاية` = `كفايه`.
 *
 * 🔴 الخطوة 5 **تطبيع مدخلات، لا مخرجات.** الزبون الأردني على لوحة مفاتيح
 *    عربية يرسل `٥` لا `5`، وبدونها طلبه يسقط كاملا وبلا تفسير. قاعدة
 *    «الأرقام غربية» تحكم ما نرسله نحن، وهذا ما نستقبله.
 *
 * 🔴 القص من الطرفين فقط. `هاد كل شي` مسافاته داخلية وتبقى — تقليصها إلى
 *    مسافة واحدة كافٍ، وحذفها يخلط الأمر بغيره.
 */
export function normalizeArabic(input: string): string {
  return input
    .replace(/[أإآ]/gu, "ا") // أ إ آ → ا
    .replace(/ة/gu, "ه") // ة → ه
    .replace(/ى/gu, "ي") // ى → ي
    .replace(DIACRITICS_AND_TATWEEL, "")
    .replace(ARABIC_INDIC_DIGITS, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/\s+/gu, " ")
    .replace(NON_ALNUM_HEAD, "")
    .replace(NON_ALNUM_TAIL, "");
}

