/**
 * مهلة الجلسة — القرار الصافي (بريف ح §2).
 *
 * جلسة نشطة سكتت `idleMinutes` دقيقة **أو أكتر** منتهية. `>=` مش `>`: البريف
 * بيقول «60 دقيقة أو أكتر»، فجلسة سكتت 60:00 بالضبط منتهية.
 *
 * 🔴 `idleSeconds` جاية من القاعدة (`now() - last_message_at`)، **مش من ساعة
 *    Node** — بريف ح §0. ولهيك هي وسيط هون مش حساب: الدالة ما بتعرف شو
 *    الساعة، فما في طريقة تقرأ ساعة غلط. والحد بينفحص بأرقام ثابتة (3599 و3600)
 *    بدل قاعدة بتمشي ساعتها بين تجهيز الاختبار والفحص.
 */
export function isSessionExpired(
  idleSeconds: number,
  idleMinutes: number,
): boolean {
  return idleSeconds >= idleMinutes * 60;
}
